#!/usr/bin/env python3
"""App translations: collect keys, check language files, generate I18nData.kt.

  python3 scripts/i18n/gen.py            # check + write composeApp/.../i18n/I18nData.kt
  python3 scripts/i18n/gen.py --keys     # also write composeApp/i18n/_keys.json (all English keys, for translators)

Source of truth: composeApp/i18n/<lang>.json – {"English key": "translation"}.
Keys are the English texts passed to tr("…") / trn(n, "one", "other") in the Kotlin code
(a plural key is "one|other"; its value is the language's plural forms joined with "|",
in CLDR order – see Plural in I18n.kt). {0}, {1} … are values; translations may reorder them.
Fails (exit 1) if a language misses keys, has unknown keys, or drops/invents a {n} placeholder.
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "composeApp" / "src"
I18N = ROOT / "composeApp" / "i18n"
LOCALES = SRC / "androidMain" / "res" / "xml" / "locales_config.xml"
OUT = SRC / "commonMain" / "kotlin" / "app" / "anylap" / "i18n" / "I18nData.kt"

ESC = {"n": "\n", "t": "\t", '"': '"', "\\": "\\", "$": "$", "'": "'", "r": "\r"}


def read_lit(src, i):
    """Kotlin "…" literal starting at src[i] == '"' -> (value, end). Templates are not allowed in keys."""
    assert src[i] == '"'
    j, out = i + 1, []
    while src[j] != '"':
        c = src[j]
        if c == "\\":
            n = src[j + 1]
            if n == "u":
                out.append(chr(int(src[j + 2:j + 6], 16))); j += 6; continue
            out.append(ESC[n]); j += 2; continue
        if c == "$" and (src[j + 1] == "{" or src[j + 1].isalpha()):
            raise ValueError(f"template inside a translation key near: {src[i:i + 80]!r}")
        out.append(c); j += 1
    return "".join(out), j + 1


def keys_in_code():
    keys = {}
    for f in sorted(SRC.rglob("*.kt")):
        if f.parent == OUT.parent:  # I18n.kt / I18nData.kt themselves
            continue
        src = f.read_text()
        for m in re.finditer(r'\btr\(\s*"', src):
            v, _ = read_lit(src, m.end() - 1)
            keys.setdefault(v, f"{f.relative_to(SRC)}")
        for m in re.finditer(r'\btrn\(', src):
            # trn(n, "one", "other", ...) – skip the count expression to the first string
            k = src.index('"', m.end())
            one, e = read_lit(src, k)
            k2 = src.index('"', e)
            other, _ = read_lit(src, k2)
            keys.setdefault(one + "|" + other, f"{f.relative_to(SRC)}")
    return keys


def placeholders(s):
    return sorted(set(re.findall(r"\{(\d+)\}", s)))


def kt_raw(s):
    # Escape for a Kotlin raw string: only '$' and '"""' are special.
    assert '"""' not in s
    return s.replace("$", "${'$'}")


def enc(s):
    return s.replace("\\", "\\\\").replace("\t", "\\t").replace("\n", "\\n")


def main():
    keys = keys_in_code()
    langs = sorted(p.stem for p in I18N.glob("*.json") if not p.stem.startswith("_"))
    bad = False
    tables = {}
    for lang in langs:
        t = json.loads((I18N / f"{lang}.json").read_text())
        missing = [k for k in keys if k not in t]
        unknown = [k for k in t if k not in keys]
        wrong = []
        for k, v in t.items():
            if k not in keys:
                continue
            if "|" in k and k.count("|") == 1:
                kp = placeholders(k.split("|")[1]); forms = v.split("|")
                if any(set(placeholders(f)) - set(kp + ["0"]) for f in forms):
                    wrong.append(k)
            elif set(placeholders(v)) - set(placeholders(k)):
                wrong.append(k)
        for name, lst in (("missing", missing), ("unknown", unknown), ("bad placeholders", wrong)):
            if lst:
                bad = True
                print(f"{lang}: {len(lst)} {name}:")
                for k in lst[:40]:
                    print("   ", json.dumps(k, ensure_ascii=False), "  <-", keys.get(k, ""))
        tables[lang] = {k: v for k, v in t.items() if k in keys}
    if "--keys" in sys.argv:
        (I18N / "_keys.json").write_text(json.dumps({k: keys[k] for k in sorted(keys)}, ensure_ascii=False, indent=1) + "\n")
    body = []
    for lang in langs:
        lines = "\n".join(enc(k) + "\t" + enc(v) for k, v in tables[lang].items())
        body.append(f'        "{lang}" -> parse("""\n{kt_raw(lines)}\n""")')
    code = f'''// GENERATED by scripts/i18n/gen.py from composeApp/i18n/*.json – do not edit.
package app.anylap.i18n

internal object I18nData {{
    /** Languages with a translation table (English is the keys themselves). */
    val LANGS = listOf("en", {", ".join(f'"{l}"' for l in langs)})

    fun table(lang: String): Map<String, String> = when (lang) {{
{chr(10).join(body)}
        else -> emptyMap()
    }}

    private fun parse(data: String): Map<String, String> {{
        val m = HashMap<String, String>()
        for (line in data.lineSequence()) {{
            val tab = line.indexOf('\\t')
            if (tab <= 0) continue
            m[dec(line.substring(0, tab))] = dec(line.substring(tab + 1))
        }}
        return m
    }}

    private fun dec(s: String): String {{
        if ('\\\\' !in s) return s
        val b = StringBuilder(s.length)
        var i = 0
        while (i < s.length) {{
            val c = s[i]
            if (c == '\\\\' && i + 1 < s.length) {{
                b.append(when (s[i + 1]) {{ 'n' -> '\\n'; 't' -> '\\t'; else -> s[i + 1] }}); i += 2
            }} else {{ b.append(c); i++ }}
        }}
        return b.toString()
    }}
}}
'''
    OUT.write_text(code)
    loc = "\n".join(f'    <locale android:name="{l}" />' for l in ["en"] + langs)
    LOCALES.write_text('<?xml version="1.0" encoding="utf-8"?>\n<!-- GENERATED by scripts/i18n/gen.py: languages offered under Android Settings → Apps → AnyLap → Language. -->\n'
                       f'<locale-config xmlns:android="http://schemas.android.com/apk/res/android">\n{loc}\n</locale-config>\n')
    print(f"{len(keys)} keys in code; languages: {', '.join(langs) or '(none)'} -> {OUT.relative_to(ROOT)}")
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
